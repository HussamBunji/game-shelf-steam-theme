// Generates src/css/web-styles/<id>.css (the store-page rules of each style) from src/styles/*.css.
// Millennium injects only the *default* style into store/community pages, so those pages
// carry all four variable sets and webkit.js picks the right one (html[data-rfs-style=…]).
//   node tools/build.mjs
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const styles = ['classic', 'neon', 'glass', 'original', 'space', 'material', 'terminal', 'vault', 'vinyl', 'cork', 'arcade', 'magazine', 'cupertino', 'cyberpunk', 'shelter', 'xmb',
  'steam-oled', 'steam-graphite', 'steam-midnight', 'steam-forest', 'steam-wine', 'steam-royal', 'steam-coffee', 'steam-ocean']; // steam-*: tints of Steam Original
// One file per style: src/css/web-styles/<id>.css = that style's rules (scoped html[data-rfs-style="<id>"]) + the
// shared theme icons. webkit.js links only the active one. (All styles in one file made every store page slow: the
// browser tried the other styles' ~3,000 selectors against every element on every style pass.)
const HEAD = '/* GENERATED by tools/build.mjs from src/styles/*.css — do not edit by hand */\n';
const icons = readFileSync(path.join(ROOT, 'src/css/icons.css'), 'utf8');
export const webStyle = s => {
  let css = readFileSync(path.join(ROOT, 'src/styles', s + '.css'), 'utf8');
  // the colour variants are "original" on web pages and name their palette with html[data-rfs-tint]: their eight
  // palette blocks (one selector each) travel in Original's file, or src/js/tint.js finds no palette on a store page
  if (s === 'original') for (const t of styles) if (/^steam-/.test(t) && existsSync(path.join(ROOT, 'src/styles', t + '.css'))) css += '\n' + readFileSync(path.join(ROOT, 'src/styles', t + '.css'), 'utf8').replace(/(^|[^:]):root\s*\{/gm, `$1html[data-rfs-style="${t}"] {`);
  return HEAD + '\n' + css.replace(/:root:root\s*\{/g, `html[data-rfs-style="${s}"][data-rfs-style] {`).replace(/(^|[^:]):root\s*\{/gm, `$1html[data-rfs-style="${s}"] {`) + '\n\n' + icons;
};
mkdirSync(path.join(ROOT, 'src/css/web-styles'), { recursive: true });
for (const s of styles) {
  if (!existsSync(path.join(ROOT, 'src/styles', s + '.css'))) { console.log('missing style', s); continue; }
  if (/^steam-/.test(s)) continue; // a colour variant is "original" on web pages (html[data-rfs-tint] names its palette)
  writeFileSync(path.join(ROOT, 'src/css/web-styles', s + '.css'), webStyle(s));
}
// the old all-in-one file: nothing loads it any more (kept as a stub so an older webkit.css import finds a file)
writeFileSync(path.join(ROOT, 'src/css/webkit-styles.css'), '/* replaced by src/css/web-styles/<id>.css (tools/build.mjs) */\n');
// Arabic Steam interface: src/lang/steam-ar.json (token → Arabic, edit this one) → src/lang/steam-ar.js (loaded by shelf.js)
const arSrc = path.join(ROOT, 'src/lang/steam-ar.json');
if (existsSync(arSrc)) {
  const tokens = JSON.parse(readFileSync(arSrc, 'utf8'));
  writeFileSync(path.join(ROOT, 'src/lang/steam-ar.js'),
    `/* GENERATED by tools/build.mjs from src/lang/steam-ar.json — Arabic for Steam's own interface (${Object.keys(tokens).length} strings) */\nwindow.__rfsSteamAr = ${JSON.stringify(tokens)};\n`);
  console.log('built src/lang/steam-ar.js —', Object.keys(tokens).length, 'strings');
}
console.log('built src/css/web-styles/<id>.css');
