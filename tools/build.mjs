// Generates src/css/webkit-styles.css from src/styles/*.css.
// Millennium injects only the *default* style into store/community pages, so those pages
// carry all four variable sets and webkit.js picks the right one (html[data-rfs-style=…]).
//   node tools/build.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const styles = ['classic', 'neon', 'glass', 'original', 'space', 'material'];
let out = '/* GENERATED by tools/build.mjs from src/styles/*.css — do not edit by hand */\n';
for (const s of styles) {
  const css = readFileSync(path.join(ROOT, 'src/styles', s + '.css'), 'utf8');
  out += '\n' + css.replace(/:root:root\s*\{/g, `html[data-rfs-style="${s}"][data-rfs-style] {`).replace(/(^|[^:]):root\s*\{/gm, `$1html[data-rfs-style="${s}"] {`) + '\n';
}
// shared theme icons (the library window imports icons.css itself)
out += '\n' + readFileSync(path.join(ROOT, 'src/css/icons.css'), 'utf8');
writeFileSync(path.join(ROOT, 'src/css/webkit-styles.css'), out);
// Arabic Steam interface: src/lang/steam-ar.json (token → Arabic, edit this one) → src/lang/steam-ar.js (loaded by shelf.js)
const arSrc = path.join(ROOT, 'src/lang/steam-ar.json');
if (existsSync(arSrc)) {
  const tokens = JSON.parse(readFileSync(arSrc, 'utf8'));
  writeFileSync(path.join(ROOT, 'src/lang/steam-ar.js'),
    `/* GENERATED by tools/build.mjs from src/lang/steam-ar.json — Arabic for Steam's own interface (${Object.keys(tokens).length} strings) */\nwindow.__rfsSteamAr = ${JSON.stringify(tokens)};\n`);
  console.log('built src/lang/steam-ar.js —', Object.keys(tokens).length, 'strings');
}
console.log('built src/css/webkit-styles.css');
