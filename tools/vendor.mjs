// Bundles community Millennium themes (MIT licensed) as extra styles of this theme.
//   1) git clone them into third_party/  (see VENDORS)
//   2) node tools/vendor.mjs
// Copies each theme into src/vendor/<id>/ (keeping its LICENSE) and writes src/vendor/<id>/rfs-manifest.js:
// which of its CSS/JS files go into which Steam window / web page — rebuilt from the theme's own skin.json
// (Patches, RootColors, Steam-WebKit, the *default* value of every Condition, and legacy *.custom.css files).
// skin.js (Steam windows) and webkit.js (store/community) load those files only while that style is chosen.
import { readFileSync, writeFileSync, existsSync, rmSync, cpSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const VENDORS = [
  { id: 'space', dir: 'third_party/spacetheme', repo: 'https://github.com/SpaceTheme/Steam', js: true },
  { id: 'material', dir: 'third_party/material', repo: 'https://github.com/kuska1/Material-Theme', js: false },
];
const WEB = ['https://.*\\.steampowered\\.com(/.*)?', 'https://steamcommunity\\.com(/.*)?'];
const LEGACY = { // SteamFriendsPatcher-style files Millennium loads by name
  'libraryroot.custom.css': ['^Steam$'],
  'friends.custom.css': ['.friendsui-container', '^Friends List$'],
  'menu.custom.css': ['Menu$', 'SuperNav$'],
  'notifications.custom.css': ['^notificationtoasts_'],
};
const SKIP = new Set(['.git', '.github', 'tests', 'node_modules']);
// Millennium tests a pattern against the window title (Steam windows) or the URL (web pages), so ".*"
// also lands on store/community pages; ".class" / "[attr]" patterns are selectors for Steam windows
const isSelector = p => /^(\.[A-Za-z_-]|\[)/.test(p);
const isUrl = p => !isSelector(p) && (/^\^?https?/.test(p) || (() => { try { return new RegExp(p).test('https://store.steampowered.com/app/1/'); } catch (e) { return false; } })());
const isWin = p => !/^\^?https?/.test(p);
const clean = p => String(p || '').replace(/^\.\//, '').replace(/\\/g, '/');

for (const v of VENDORS) {
  const src = path.join(ROOT, v.dir);
  if (!existsSync(path.join(src, 'skin.json'))) { console.log(`skip ${v.id}: ${v.dir} not cloned`); continue; }
  const skin = JSON.parse(readFileSync(path.join(src, 'skin.json'), 'utf8').replace(/^﻿/, ''));
  const win = [], web = [];
  const seen = new Set();
  const add = (patterns, css, js) => {
    css = clean(css); js = v.js ? clean(js) : '';
    if (css && !existsSync(path.join(src, css))) css = '';
    if (js && !existsSync(path.join(src, js))) js = '';
    if (!css && !js) return;
    const w = patterns.filter(isWin), u = patterns.filter(isUrl);
    const key = (css || '-') + '|' + (js || '-') + '|' + patterns.join(',');
    if (seen.has(key)) return;
    seen.add(key);
    if (w.length) win.push({ m: w, ...(css && { css }), ...(js && { js }) });
    if (u.length) web.push({ m: u, ...(css && { css }), ...(js && { js }) });
  };
  if (skin.RootColors) add(['.*'], skin.RootColors);
  for (const p of skin.Patches || []) add([p.MatchRegexString], p.TargetCss, p.TargetJs);
  if (skin['Steam-WebKit']) add(WEB, skin['Steam-WebKit']);
  const patched = new Set((skin.Patches || []).map(p => clean(p.TargetCss)));
  for (const [f, m] of Object.entries(LEGACY)) if (!patched.has(f) && existsSync(path.join(src, f))) add(m, f);
  for (const c of Object.values(skin.Conditions || {})) {
    const d = (c.values || {})[c.default];
    if (!d) continue;
    if (d.TargetCss) add(d.TargetCss.affects || ['.*'], d.TargetCss.src);
    if (d.TargetJs) add(d.TargetJs.affects || ['.*'], '', d.TargetJs.src);
  }

  const dest = path.join(ROOT, 'src/vendor', v.id);
  rmSync(dest, { recursive: true, force: true });
  cpSync(src, dest, { recursive: true, filter: f => !SKIP.has(path.basename(f)) && !(statSync(f).isFile() && /\.(gif|mp4|webm)$/i.test(f)) });
  // slider conditions: Millennium turns them into CSS variables (e.g. SpaceTheme's --st-store-max-width: 1200px)
  const sliders = Object.values(skin.Conditions || {}).filter(c => c.slider && c.slider.cssVariable)
    .map(c => `  ${c.slider.cssVariable}: ${c.default}${c.slider.unit || ''};`);
  if (sliders.length) {
    writeFileSync(path.join(dest, 'rfs-sliders.css'), `/* generated by tools/vendor.mjs — default values of ${skin.name}'s slider settings */\n:root {\n${sliders.join('\n')}\n}\n`);
    win.unshift({ m: ['.*'], css: 'rfs-sliders.css' });
    web.unshift({ m: WEB, css: 'rfs-sliders.css' });
  }
  const man = { id: v.id, name: skin.name, author: skin.author, repo: v.repo, license: 'MIT', win, web };
  writeFileSync(path.join(dest, 'rfs-manifest.js'),
    `/* generated by tools/vendor.mjs — ${skin.name} (${v.repo}, MIT) */\n(window.__rfsVendors = window.__rfsVendors || {})[${JSON.stringify(v.id)}] = ${JSON.stringify(man, null, 1)};\n`);
  console.log(`${v.id}: ${win.length} window entries, ${web.length} web entries → src/vendor/${v.id}`);
}
